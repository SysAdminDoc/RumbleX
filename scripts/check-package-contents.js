#!/usr/bin/env node
'use strict';

// Every runtime file in extension/ must appear in BOTH release packages.
//
// The pack list used to be repeated verbatim in three archiver branches of
// build.sh (`zip`, Windows `tar.exe`, `bsdtar`) with only a single substring of
// it guarded, so adding a runtime file and forgetting one branch shipped a
// package that was silently missing it. The list is declared once now, and this
// checks the actual archives rather than the script that wrote them.
//
// Run after `extension/build.sh`. Skips cleanly when the packages are absent so
// a source-only checkout does not fail the suite.

const assert = require('assert/strict');
const fs = require('fs');
const path = require('path');
const { readArchive } = require('./zip-utils');

const ROOT = path.resolve(__dirname, '..');
const EXT = path.join(ROOT, 'extension');
const PACKAGES = [
    { label: 'Chrome', file: path.join(ROOT, 'RumbleX-chrome.zip'), manifest: 'manifest.json' },
    { label: 'Firefox', file: path.join(ROOT, 'RumbleX-firefox-amo-unsigned.zip'), manifest: 'manifest-firefox.json' },
];

const missingPackages = PACKAGES.filter((pkg) => !fs.existsSync(pkg.file));
if (missingPackages.length) {
    console.log(`Package contents guard skipped: run extension/build.sh first (missing ${missingPackages.map((p) => path.basename(p.file)).join(', ')}).`);
    process.exit(0);
}

// Source of truth: the single declaration in build.sh.
const buildScript = fs.readFileSync(path.join(EXT, 'build.sh'), 'utf8');
const declaredFiles = (buildScript.match(/^PACK_FILES="([^"]+)"/m) || [])[1];
const declaredDirs = (buildScript.match(/^PACK_DIRS="([^"]+)"/m) || [])[1];
assert.ok(declaredFiles, 'build.sh no longer declares PACK_FILES');
assert.ok(declaredDirs, 'build.sh no longer declares PACK_DIRS');

const packFiles = declaredFiles.trim().split(/\s+/);
const packDirs = declaredDirs.trim().split(/\s+/);

// Every top-level runtime file on disk must be declared. This is the half that
// catches "added a new runtime file and forgot to package it at all".
const EXCLUDED_FROM_PACKAGES = new Set([
    'manifest.json',            // supplied per-package by the staging step
    'manifest-firefox.json',    // ditto
    'build.sh',                 // the builder itself
    'manifest-chrome-backup.json',
]);
const onDisk = fs.readdirSync(EXT, { withFileTypes: true });
const runtimeFiles = onDisk
    .filter((entry) => entry.isFile())
    .map((entry) => entry.name)
    .filter((name) => /\.(js|html|css|json)$/.test(name))
    .filter((name) => !EXCLUDED_FROM_PACKAGES.has(name));

const undeclared = runtimeFiles.filter((name) => !packFiles.includes(name));
assert.deepEqual(undeclared, [],
    `runtime files in extension/ that build.sh does not package: ${undeclared.join(', ')}`);

const runtimeDirs = onDisk
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    // `_metadata/` is generated by Chrome when the extension is loaded unpacked
    // (verified_contents.json). It is browser output, not source, and must stay
    // out of the packages.
    .filter((name) => !name.startsWith('.') && name !== 'node_modules' && name !== '_metadata');
const undeclaredDirs = runtimeDirs.filter((name) => !packDirs.includes(name));
assert.deepEqual(undeclaredDirs, [],
    `directories in extension/ that build.sh does not package: ${undeclaredDirs.join(', ')}`);

const runtimeSources = new Map(packFiles.map((name) => [name, path.join(EXT, name)]));
const collectDirectory = (directory) => {
    const root = path.join(EXT, directory);
    const visit = (current) => {
        for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
            const absolute = path.join(current, entry.name);
            if (entry.isDirectory()) visit(absolute);
            else if (entry.isFile()) {
                const relative = path.relative(EXT, absolute).split(path.sep).join('/');
                runtimeSources.set(relative, absolute);
            }
        }
    };
    visit(root);
};
for (const directory of packDirs) collectDirectory(directory);

const archives = new Map();
for (const pkg of PACKAGES) {
    const archive = readArchive(pkg.file);
    archives.set(pkg.label, archive);
    const entries = [...archive.keys()];
    const fileEntrySet = new Set(entries.filter((entry) => !entry.endsWith('/')));
    const entrySet = new Set(entries.map((entry) => entry.replace(/\/$/, '')));

    const missingFiles = packFiles.filter((name) => !entrySet.has(name));
    assert.deepEqual(missingFiles, [],
        `${pkg.label} package is missing declared files: ${missingFiles.join(', ')}`);

    for (const dir of packDirs) {
        const hasAny = entries.some((entry) => entry.startsWith(dir + '/') && !entry.endsWith('/'));
        assert.ok(hasAny, `${pkg.label} package contains no files from ${dir}/`);
    }

    assert.ok(entrySet.has('manifest.json'), `${pkg.label} package has no manifest.json`);

    const expectedFiles = new Set(['manifest.json', ...runtimeSources.keys()]);
    const unexpectedFiles = [...fileEntrySet].filter((name) => !expectedFiles.has(name));
    assert.deepEqual(unexpectedFiles, [],
        `${pkg.label} package contains undeclared files: ${unexpectedFiles.join(', ')}`);

    for (const [entryName, sourcePath] of runtimeSources) {
        assert.ok(fileEntrySet.has(entryName), `${pkg.label} package is missing runtime source ${entryName}`);
        assert.equal(Buffer.compare(archive.get(entryName), fs.readFileSync(sourcePath)), 0,
            `${pkg.label} package contains stale bytes for ${entryName}`);
    }

    const manifestSource = fs.readFileSync(path.join(EXT, pkg.manifest));
    assert.equal(Buffer.compare(archive.get('manifest.json'), manifestSource), 0,
        `${pkg.label} package manifest differs from extension/${pkg.manifest}`);
    const archivedManifest = JSON.parse(archive.get('manifest.json').toString('utf8'));
    assert.equal(archivedManifest.manifest_version, pkg.label === 'Chrome' ? 3 : 2,
        `${pkg.label} package has the wrong manifest version`);
    const sourceManifest = JSON.parse(manifestSource.toString('utf8'));
    assert.deepEqual(archivedManifest.content_scripts, sourceManifest.content_scripts,
        `${pkg.label} package content-script order differs from extension/${pkg.manifest}`);

    // The working tree must never leak build scaffolding into a release.
    for (const forbidden of ['manifest-firefox.json', 'manifest-chrome-backup.json', 'build.sh', '_metadata']) {
        assert.ok(!entrySet.has(forbidden),
            `${pkg.label} package must not contain ${forbidden}`);
    }
}

// The two packages must differ only in manifest content, never in file set.
// Directory records are optional ZIP metadata. Compare shipped files so a
// deterministic writer does not have to imitate an archiver's directory-list
// convention to prove Chrome and Firefox contain the same runtime.
const chromeEntries = new Set([...archives.get('Chrome').keys()].filter((entry) => !entry.endsWith('/')));
const firefoxEntries = new Set([...archives.get('Firefox').keys()].filter((entry) => !entry.endsWith('/')));
const onlyChrome = [...chromeEntries].filter((e) => !firefoxEntries.has(e));
const onlyFirefox = [...firefoxEntries].filter((e) => !chromeEntries.has(e));
assert.deepEqual(onlyChrome, [], `files present only in the Chrome package: ${onlyChrome.join(', ')}`);
assert.deepEqual(onlyFirefox, [], `files present only in the Firefox package: ${onlyFirefox.join(', ')}`);

// The staged Firefox manifest must actually be MV2, and Chrome's MV3 — proving
// the swap happened in staging and not by mutating the working tree.
const workingManifest = JSON.parse(fs.readFileSync(path.join(EXT, 'manifest.json'), 'utf8'));
assert.equal(workingManifest.manifest_version, 3,
    'extension/manifest.json is not MV3 — an interrupted build may have left the Firefox manifest in place');

console.log(`Package contents guard OK: ${runtimeSources.size} runtime files match source bytes, with verified MV3 and MV2 manifests.`);
